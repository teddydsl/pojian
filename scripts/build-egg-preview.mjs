import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const source = resolve(root, 'public/assets/models/fuzzy-egg-game.glb');
const destination = resolve(root, 'public/assets/models/fuzzy-egg-game.embedded.js');
const data = readFileSync(source);
if (data.toString('ascii', 0, 4) !== 'glTF') throw new Error('Cocoon asset is not a GLB file');
const sha256 = createHash('sha256').update(data).digest('hex');
writeFileSync(destination, `/* Textured cocoon for file:// game review; generated by scripts/build-egg-preview.mjs. */\nwindow.PojianEggGlb = { sha256: ${JSON.stringify(sha256)}, byteLength: ${data.length}, base64: ${JSON.stringify(data.toString('base64'))} };\n`);
console.log(`Embedded cocoon GLB: ${data.length} bytes, ${sha256.slice(0, 12)}`);
