import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Embed the approved local GLB so file:// review pages need no server.
const root = resolve(import.meta.dirname, '..');
const source = resolve(root, 'public/assets/models/felt-forest-with-mushrooms.glb');
const destination = resolve(root, 'public/assets/models/felt-forest-with-mushrooms.embedded.js');
const data = readFileSync(source);
if (data.toString('ascii', 0, 4) !== 'glTF') throw new Error('Forest asset is not a GLB file');
const sha256 = createHash('sha256').update(data).digest('hex');
writeFileSync(destination, `/* Forest scene for file:// game review; generated by scripts/build-forest-preview.mjs. */\nwindow.PojianForestGlb = { sha256: ${JSON.stringify(sha256)}, byteLength: ${data.length}, base64: ${JSON.stringify(data.toString('base64'))} };\n`);
console.log(`Embedded forest GLB: ${data.length} bytes, ${sha256.slice(0, 12)}`);
