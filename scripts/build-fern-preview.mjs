import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
for (const [name, globalName] of [
  ['fern-plant-game', 'PojianFernGlb'],
  ['fern-plant-ground', 'PojianFernGroundGlb'],
]) {
  const data = readFileSync(resolve(root, `public/assets/models/${name}.glb`));
  if (data.toString('ascii', 0, 4) !== 'glTF') throw new Error(`${name} is not a GLB file`);
  const sha256 = createHash('sha256').update(data).digest('hex');
  writeFileSync(resolve(root, `public/assets/models/${name}.embedded.js`),
    `/* Local fern GLB for file:// review; generated by scripts/build-fern-preview.mjs. */\nwindow.${globalName} = { sha256: ${JSON.stringify(sha256)}, byteLength: ${data.length}, base64: ${JSON.stringify(data.toString('base64'))} };\n`);
  console.log(`Embedded ${name}: ${data.length} bytes, ${sha256.slice(0, 12)}`);
}
