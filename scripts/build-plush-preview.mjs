import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Keep this bundle separate from the model used by the playable game.
// Embedding lets the existing local review HTML run by double-clicking file://.
const root = resolve(import.meta.dirname, '..');
const source = resolve(root, 'public/assets/models/hedgehog-plush-single-colored.glb');
const destination = resolve(root, 'public/assets/models/hedgehog-plush-single-colored.embedded.js');
const data = readFileSync(source);
if (data.toString('ascii', 0, 4) !== 'glTF') throw new Error('Not a GLB file');
const sha256 = createHash('sha256').update(data).digest('hex');
writeFileSync(destination, `/* Approved single-hedgehog game model; generated by scripts/build-plush-preview.mjs. */\nwindow.PojianHedgehogGlb = { sha256: ${JSON.stringify(sha256)}, byteLength: ${data.length}, base64: ${JSON.stringify(data.toString('base64'))} };\n`);
console.log(`Embedded single hedgehog GLB: ${data.length} bytes, ${sha256.slice(0, 12)}`);
