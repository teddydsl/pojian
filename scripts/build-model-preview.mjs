import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Direct file:// review pages cannot fetch a sibling GLB in common browsers.
// Embed the supplied binary in a classic script only for the local preview.
const root = resolve(import.meta.dirname, '..');
const asset = resolve(root, 'public/assets/models/hedgehog-felt.glb');
const output = resolve(root, 'public/assets/models/hedgehog-felt.embedded.js');
const glb = readFileSync(asset);
if (glb.toString('ascii', 0, 4) !== 'glTF') throw new Error('hedgehog-felt.glb is not a GLB file');
const sha256 = createHash('sha256').update(glb).digest('hex');
writeFileSync(output, `/* Local review copy of hedgehog-felt.glb; generated by npm run build:model-preview. */\nwindow.PojianFeltGlb = { sha256: ${JSON.stringify(sha256)}, byteLength: ${glb.length}, base64: ${JSON.stringify(glb.toString('base64'))} };\n`);
console.log(`Embedded ${glb.length} GLB bytes for file:// preview (${sha256.slice(0, 12)})`);
